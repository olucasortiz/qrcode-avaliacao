import { Router } from 'express';
import { authenticate } from '../middlewares/authMiddleware.js';
import * as pesquisas from '../controllers/pesquisaController.js';
import * as perguntas from '../controllers/perguntaController.js';
import * as feedbacks from '../controllers/feedbackController.js';
import { adminLimiter, exportLimiter } from '../middlewares/rateLimitMiddleware.js';
import * as pontos from '../controllers/pontoColetaController.js';
import { dashboard, resultados } from '../controllers/resultadoController.js';

const router = Router();
router.use(['/pesquisas', '/pontos', '/dashboard'], adminLimiter, authenticate);
router.get('/pesquisas', pesquisas.listar);
router.post('/pesquisas', pesquisas.criar);
router.get('/pesquisas/:id', pesquisas.obter);
router.patch('/pesquisas/:id', pesquisas.atualizar);
router.delete('/pesquisas/:id', pesquisas.excluir);
router.post('/pesquisas/:id/publicar', pesquisas.publicar);
router.get('/pesquisas/:pesquisaId/perguntas', perguntas.listar);
router.post('/pesquisas/:pesquisaId/perguntas', perguntas.criar);
router.get('/pesquisas/:pesquisaId/perguntas/:id', perguntas.obter);
router.patch('/pesquisas/:pesquisaId/perguntas/:id', perguntas.atualizar);
router.delete('/pesquisas/:pesquisaId/perguntas/:id', perguntas.excluir);
router.get('/pesquisas/:id/feedbacks', feedbacks.listar);
router.get('/pesquisas/:id/exportar', exportLimiter, feedbacks.exportar);
router.get('/pesquisas/:pesquisaId/pontos', pontos.listar);
router.post('/pesquisas/:pesquisaId/pontos', pontos.criar);
router.get('/pontos/:id/qrcode', pontos.qrcode);
router.get('/pontos/:id', pontos.obter);
router.patch('/pontos/:id', pontos.atualizar);
router.delete('/pontos/:id', pontos.excluir);
router.get('/dashboard', dashboard);
router.get('/pesquisas/:id/resultados', resultados);
export default router;
